-- 5. VIEW
-- ============================================================

CREATE OR REPLACE VIEW student_result_report AS
SELECT
    s.student_id,
    s.student_name,
    s.email,
    e.exam_name,
    ea.attempt_id,
    r.result_id,
    r.total_questions,
    r.attempted,
    r.correct,
    r.wrong,
    r.score,
    r.percentage,
    r.result_time
FROM student s
JOIN exam_attempt ea ON s.student_id = ea.student_id
JOIN exam e ON ea.exam_id = e.exam_id
JOIN result r ON ea.attempt_id = r.attempt_id;

-- ============================================================
-- 6. STORED FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION get_percentage(
    p_score NUMBER,
    p_total_marks NUMBER
)
RETURN NUMBER
IS
BEGIN
    IF p_total_marks = 0 THEN
        RETURN 0;
    END IF;

    RETURN ROUND((p_score / p_total_marks) * 100, 2);
END;
/

-- ============================================================
-- 7. STORED PROCEDURE
-- ============================================================

CREATE OR REPLACE PROCEDURE get_student_results(
    p_student_id IN NUMBER,
    p_cursor OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN p_cursor FOR
        SELECT
            exam_name,
            attempt_id,
            total_questions,
            attempted,
            correct,
            wrong,
            score,
            percentage,
            result_time
        FROM student_result_report
        WHERE student_id = p_student_id
        ORDER BY result_time DESC;
END;
/

-- ============================================================
-- 8. PROCEDURE USING CURSOR
-- ============================================================

CREATE OR REPLACE PROCEDURE show_student_summary
IS
    CURSOR c_students IS
        SELECT student_id, student_name
        FROM student
        ORDER BY student_id;
BEGIN
    FOR r IN c_students LOOP
        DBMS_OUTPUT.PUT_LINE(
            'Student ID: ' || r.student_id ||
            ' | Name: ' || r.student_name
        );
    END LOOP;
END;
/

-- ============================================================
-- 9. TRIGGER
-- ============================================================

CREATE OR REPLACE TRIGGER trg_result_audit
AFTER INSERT ON result
FOR EACH ROW
BEGIN
    INSERT INTO result_audit(
        result_id,
        attempt_id,
        score,
        action_time,
        action_type
    )
    VALUES(
        :NEW.result_id,
        :NEW.attempt_id,
        :NEW.score,
        SYSTIMESTAMP,
        'RESULT_CREATED'
    );
END;
/

COMMIT;

