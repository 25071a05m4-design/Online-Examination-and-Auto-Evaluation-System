    ea.student_id,
    r.score
FROM exam_attempt ea
JOIN result r ON ea.attempt_id = r.attempt_id
WHERE r.score > (
    SELECT AVG(score)
    FROM result
);

-- CTE
WITH exam_summary AS (
    SELECT
        ea.student_id,
        SUM(r.score) total_score
    FROM exam_attempt ea
    JOIN result r ON ea.attempt_id = r.attempt_id
    GROUP BY ea.student_id
)
SELECT *
FROM exam_summary;

