-- 2. TABLES - NORMALIZED DESIGN
-- ============================================================

CREATE TABLE student (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(120) NOT NULL,
    password VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (student_id),
    CONSTRAINT uq_student_email UNIQUE (email)
);

CREATE TABLE exam (
    exam_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    exam_name VARCHAR2(150) NOT NULL,
    duration_minutes NUMBER(4) NOT NULL,
    total_marks NUMBER(6,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_exam PRIMARY KEY (exam_id),
    CONSTRAINT chk_exam_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_exam_marks CHECK (total_marks >= 0)
);

CREATE TABLE question (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    exam_id NUMBER NOT NULL,
    question_text VARCHAR2(1000) NOT NULL,
    marks NUMBER(5,2) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_question PRIMARY KEY (question_id),
    CONSTRAINT fk_question_exam FOREIGN KEY (exam_id)
        REFERENCES exam(exam_id),
    CONSTRAINT chk_question_marks CHECK (marks > 0)
);

CREATE TABLE question_option (
    option_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    question_id NUMBER NOT NULL,
    option_label CHAR(1) NOT NULL,
    option_text VARCHAR2(500) NOT NULL,
    is_correct CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_question_option PRIMARY KEY (option_id),
    CONSTRAINT fk_option_question FOREIGN KEY (question_id)
        REFERENCES question(question_id) ON DELETE CASCADE,
    CONSTRAINT uq_question_option UNIQUE (question_id, option_label),
    CONSTRAINT chk_option_label CHECK (option_label IN ('A','B','C','D')),
    CONSTRAINT chk_option_correct CHECK (is_correct IN ('Y','N'))
);

CREATE TABLE exam_attempt (
    attempt_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id NUMBER NOT NULL,
    exam_id NUMBER NOT NULL,
    start_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    end_time TIMESTAMP,
    status VARCHAR2(20) DEFAULT 'STARTED' NOT NULL,
    CONSTRAINT pk_exam_attempt PRIMARY KEY (attempt_id),
    CONSTRAINT fk_attempt_student FOREIGN KEY (student_id)
        REFERENCES student(student_id),
    CONSTRAINT fk_attempt_exam FOREIGN KEY (exam_id)
        REFERENCES exam(exam_id),
    CONSTRAINT chk_attempt_status
        CHECK (status IN ('STARTED','SUBMITTED','CANCELLED'))
);

CREATE TABLE student_answer (
    answer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    attempt_id NUMBER NOT NULL,
    question_id NUMBER NOT NULL,
    option_id NUMBER,
    is_correct CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_student_answer PRIMARY KEY (answer_id),
    CONSTRAINT fk_answer_attempt FOREIGN KEY (attempt_id)
        REFERENCES exam_attempt(attempt_id) ON DELETE CASCADE,
    CONSTRAINT fk_answer_question FOREIGN KEY (question_id)
        REFERENCES question(question_id),
    CONSTRAINT fk_answer_option FOREIGN KEY (option_id)
        REFERENCES question_option(option_id),
    CONSTRAINT uq_attempt_question UNIQUE (attempt_id, question_id),
    CONSTRAINT chk_answer_correct CHECK (is_correct IN ('Y','N'))
);

CREATE TABLE result (
    result_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    attempt_id NUMBER NOT NULL,
    total_questions NUMBER NOT NULL,
    attempted NUMBER NOT NULL,
    correct NUMBER NOT NULL,
    wrong NUMBER NOT NULL,
    score NUMBER(8,2) NOT NULL,
    percentage NUMBER(6,2) NOT NULL,
    result_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_result PRIMARY KEY (result_id),
    CONSTRAINT uq_result_attempt UNIQUE (attempt_id),
    CONSTRAINT fk_result_attempt FOREIGN KEY (attempt_id)
        REFERENCES exam_attempt(attempt_id),
    CONSTRAINT chk_result_values CHECK (
        total_questions >= 0 AND attempted >= 0 AND
        correct >= 0 AND wrong >= 0 AND score >= 0 AND
        percentage >= 0 AND percentage <= 100
    )
);

CREATE TABLE result_audit (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    result_id NUMBER NOT NULL,
    attempt_id NUMBER NOT NULL,
    score NUMBER(8,2) NOT NULL,
    action_time TIMESTAMP DEFAULT SYSTIMESTAMP,
    action_type VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_result_audit PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_result FOREIGN KEY (result_id)
        REFERENCES result(result_id)
);

